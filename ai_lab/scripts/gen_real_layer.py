"""Export one *real* YOLOv5n layer as an exact integer test case.

Layer 10 (0-based) of the selected model is a 1x1, 256 -> 128 convolution on a
20x20 tensor.  It is the first layer whose complete input, weights and output
all fit the remaining on-chip budget (approx. 180 KiB = 41 DRM out of the 109
DRAM blocks left after CPU+video), so it is the layer this round closes end to
end.  The first layer of the model is 6x6/stride 2 and is *not* this one -- the
RTL kernel is generalised for it, but its 320x320x3 input plus 160x160x16 output
cannot be held on chip and needs the DDR tiling step.

What is produced
----------------
    layer10/cfg.txt      CIN COUT W H K STRIDE ACT S
    in.hex / w.hex       signed int8, [y][x][c] and [oc][tap][c]
    bias.hex / m.hex     int32 per output channel, right-aligned hex
    gold.hex             integer reference output, [y][x][oc]
    float.hex            dequantised float output of the same layer, 8.8 fixed
    silu_lut8.v          per-layer int8 SiLU table, s_y baked in
    report.json          scales, cosine, max error, provenance hashes

Arithmetic contract (must match conv3x3_core bit for bit):
    acc   = sum(xq*wq) + b_q
    y     = round_half_away_from_zero(acc * M >> 15)
    y     = clip(y, -128, 127)
    y     = ACT(y)          # SiLU table, scale s_y preserved
"""
import argparse
import hashlib
import json
import math
import sys
import types
from pathlib import Path

if "ultralytics" not in sys.modules:
    _u = types.ModuleType("ultralytics")
    _cu = types.ModuleType("ultralytics.utils")
    _ch = types.ModuleType("ultralytics.utils.checks")
    _ch.check_requirements = lambda *a, **k: None
    _u.utils = _cu
    _cu.checks = _ch
    sys.modules.update({"ultralytics": _u, "ultralytics.utils": _cu,
                        "ultralytics.utils.checks": _ch})

import cv2
import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
CKPT = ROOT / "data/models/yolov5n-garbage.pt"
S_SHIFT = 15


def preprocess(path, size):
    im = cv2.imread(str(path))
    h, w = im.shape[:2]
    r = min(size / h, size / w)
    nh, nw = int(round(h * r)), int(round(w * r))
    canvas = np.full((size, size, 3), 114, np.uint8)
    top, left = (size - nh) // 2, (size - nw) // 2
    canvas[top:top + nh, left:left + nw] = cv2.resize(im, (nw, nh))
    x = canvas[:, :, ::-1].transpose(2, 0, 1)[None].astype(np.float32) / 255.0
    return torch.from_numpy(np.ascontiguousarray(x))


def round_half_away(x):
    return np.sign(x) * np.floor(np.abs(x) + 0.5)


def rescale(acc, m):
    prod = acc.astype(np.int64) * m.astype(np.int64)
    half = np.where(prod < 0, -np.int64(1) << (S_SHIFT - 1), np.int64(1) << (S_SHIFT - 1))
    return (prod + half) >> S_SHIFT


def build_silu_lut(scale):
    q = np.arange(-128, 128, dtype=np.float64)
    x = q * scale
    y = x / (1.0 + np.exp(-x))
    out = np.clip(round_half_away(y / scale), -128, 127).astype(np.int16)
    return out


def emit_lut(path, table):
    lines = ["// Generated by gen_real_layer.py -- do not hand edit.",
             "// q -> round(silu(q*s_y)/s_y), s_y baked into this table.",
             "`timescale 1ns/1ps", "module silu_lut8(input wire signed [7:0] q,",
             "                  output reg signed [7:0] y);",
             "  always @(*) begin", "    case (q)"]
    for i, v in enumerate(table):
        lines.append("      %d: y = %d;" % (i - 128, int(v)))
    lines += ["      default: y = 0;", "    endcase", "  end", "endmodule", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--layer", type=int, default=10)
    ap.add_argument("--size", type=int, default=320)
    ap.add_argument("--out", default="conv_int8/layer10")
    ap.add_argument("--calib", type=int, default=8)
    a = ap.parse_args()

    sd = torch.load(CKPT, map_location="cpu", weights_only=False)
    model = sd["model"].float().eval()
    target = model.model[a.layer]
    if not target.type.endswith("Conv"):
        raise SystemExit("layer %d is %s, choose a Conv layer" % (a.layer, target.type))

    captured = {}

    def grab(_m, inp, out):
        if "in" not in captured:
            captured["in"] = inp[0].detach().clone()
            captured["out"] = out.detach().clone()

    h = target.register_forward_hook(grab)
    paths = sorted((ROOT / "data/images/indomain_test").glob("*.jpg"))
    manifest = ROOT / "data/g4/train.json"
    if manifest.exists():
        for e in list(json.loads(manifest.read_text(encoding="utf-8")).values()):
            p = ROOT / e["img"].replace("\\", "/")
            if p.exists():
                paths.append(p)
            if len(paths) >= a.calib:
                break
    paths = paths[:a.calib]

    in_max = 0.0
    out_max = 0.0
    with torch.no_grad():
        for p in paths:
            captured.clear()
            model(preprocess(p, a.size))
            in_max = max(in_max, float(captured["in"].abs().max()))
            out_max = max(out_max, float(captured["out"].abs().max()))
    h.remove()

    # fixed test image, independent of the calibration list
    test_img = ROOT / "data/images/testset/metal__metal1.jpg"
    captured.clear()
    h = target.register_forward_hook(grab)
    with torch.no_grad():
        model(preprocess(test_img, a.size))
    h.remove()
    xf = captured["in"][0].numpy()          # [cin, h, w]
    yf = captured["out"][0].numpy()         # [cout, h, w]
    cin, H, W = xf.shape
    cout = yf.shape[0]

    # fold BN into the conv so the hardware sees one weight and one bias
    fused = torch.nn.utils.fusion.fuse_conv_bn_eval(target.conv, target.bn).eval()
    wf = fused.weight.detach().numpy().reshape(cout, -1)   # [cout, cin*k*k]
    bf = fused.bias.detach().numpy()

    s_x = in_max / 127.0
    s_y = out_max / 127.0
    xq = np.clip(round_half_away(xf / s_x), -128, 127).astype(np.int8)
    wmax = np.abs(wf).max(axis=1)
    s_w = np.where(wmax > 0, wmax / 127.0, 1e-12)
    wq = np.clip(round_half_away(wf / s_w[:, None]), -128, 127).astype(np.int8)
    bq = round_half_away(bf / (s_x * s_w)).astype(np.int64)
    m = round_half_away(s_x * s_w / s_y * (1 << S_SHIFT)).astype(np.int64)

    act = xq.transpose(1, 2, 0).reshape(-1, cin).astype(np.int32)   # [H*W, cin]
    acc = act @ wq.astype(np.int32).T + bq.astype(np.int32)
    pre = np.clip(rescale(acc, m), -128, 127).astype(np.int16)
    lut = build_silu_lut(s_y)
    post = lut[pre + 128].astype(np.int8).reshape(H, W, cout)

    # float reference of exactly the same layer
    yref = yf.transpose(1, 2, 0)
    gq = post.astype(np.float64) * s_y
    cos = float((gq.ravel() @ yref.ravel())
                / (np.linalg.norm(gq) * np.linalg.norm(yref) + 1e-12))
    maxerr = float(np.abs(gq - yref).max())

    out = ROOT / a.out
    out.mkdir(parents=True, exist_ok=True)
    (out / "cfg.txt").write_text("%d %d %d %d %d %d %d %d\n"
                                 % (cin, cout, W, H, 1, 1, 2, S_SHIFT))
    (out / "in.hex").write_text("\n".join("%02x" % (v & 0xFF) for v in xq.transpose(1, 2, 0).reshape(-1).tolist()) + "\n")
    (out / "w.hex").write_text("\n".join("%02x" % (v & 0xFF) for v in wq.reshape(-1).tolist()) + "\n")
    (out / "bias.hex").write_text("\n".join("%08x" % (int(v) & 0xFFFFFFFF) for v in bq) + "\n")
    (out / "m.hex").write_text("\n".join("%08x" % (int(v) & 0xFFFFFFFF) for v in m) + "\n")
    (out / "gold.hex").write_text("\n".join("%02x" % (v & 0xFF) for v in post.reshape(-1).tolist()) + "\n")
    emit_lut(ROOT / "conv_int8/rtl/silu_lut8.v", lut)

    report = {
        "layer_index": a.layer, "layer_type": str(target.type),
        "kernel": list(target.conv.kernel_size), "stride": list(target.conv.stride),
        "padding": list(target.conv.padding), "groups": target.conv.groups,
        "activation": type(target.act).__name__,
        "cin": cin, "cout": cout, "w": W, "h": H,
        "test_image": test_img.relative_to(ROOT).as_posix(),
        "calib_images": [p.relative_to(ROOT).as_posix() for p in paths],
        "s_x": s_x, "s_y": s_y, "s_shift": S_SHIFT,
        "output_bytes": int(post.size),
        "cosine_vs_float": cos, "max_abs_error_vs_float": maxerr,
        "ckpt_sha256": hashlib.sha256(CKPT.read_bytes()).hexdigest(),
        "weight_hex_sha256": hashlib.sha256((out / "w.hex").read_bytes()).hexdigest(),
        "input_hex_sha256": hashlib.sha256((out / "in.hex").read_bytes()).hexdigest(),
        "gold_hex_sha256": hashlib.sha256((out / "gold.hex").read_bytes()).hexdigest(),
    }
    (out / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps({k: report[k] for k in
                      ("layer_index", "cin", "cout", "w", "h", "output_bytes",
                       "cosine_vs_float", "max_abs_error_vs_float", "s_x", "s_y")}, indent=2))


if __name__ == "__main__":
    main()
