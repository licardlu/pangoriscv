"""Generate the deployed 16x16 black/white font and its exact character mapping."""
import argparse
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont

LABELS={
 'TITLE':'盘古100Pro+ / 性能演示',
 'RUNNING':'演示中','WAIT':'双击开始演示','DONE':'演示完成','ERROR':'结果无效',
 'EFFICIENCY':'模拟效能评分', 'CLOCK':'当前CPU频率',
 'LOADING':'剩余秒数:', 'SOURCE':'独立CPU版本', 'REFERENCE':'参考',
 'STA_NOTE':'CPU014时序:通过',
 'MEASURE':'正式计时至少10秒','COMPLETE':'本次结果已保存',
 'CPU':'CPU:120.462MHz','TIME':'耗时:', 'CYCLES':'周期:', 'ITERATIONS':'迭代:',
 'CRC':'CRC:', 'RESULT':'结果:', 'PASS':'演示完成', 'FAIL':'未通过',
 'VALID':'有效', 'INVALID':'无效', 'PENDING':'待判定', 'WAIT_CRC':'等待校验',
 'LUTS':'参考版LUT:', 'IMPORT':'待导入', 'LUT_NOTE':'LUT来自参考版构建报告',
 'FOOTER':'KEY0 单击启停识别 / 双击切页',
 'PROGRESS':'进度', 'DEMO_NOTE':'模拟动画，非本次实测成绩',
 'PHASE1':'准备环境', 'PHASE2':'运算演示', 'PHASE3':'汇总演示',
 'DURATION':'演示时长', 'MODE':'模式', 'DEMO':'演示', 'RANGE':'评分范围',
 'NEXT':'双击切换动画 / 单击返回识别',
}

def main():
 p=argparse.ArgumentParser();p.add_argument('--source-dir',type=Path,required=True)
 p.add_argument('--live',action='store_true');a=p.parse_args()
 if a.live:
  LABELS.update(TITLE='盘古100Pro+',RUNNING='运行中',WAIT='按KEY1开始',DONE='已完成',
   EFFICIENCY='实测效能',LOADING='正在执行，请稍候',PASS='校验通过',
   DEMO_NOTE='暂停识别与媒体，运行本机CoreMark',PHASE1='计时中',PHASE2='执行官方工作负载',
   PHASE3='结果校验',DURATION='实测耗时',DEMO='实测',RANGE='测量结果',
   NEXT='KEY1 再测一次 / KEY0 双击切页',COMPLETE='完成后自动恢复应用服务',
   FOOTER='KEY1 开始 / KEY0 单击识别，双击切页')
 chars=[chr(i) for i in range(128)]
 for s in LABELS.values():
  for c in s:
   if c not in chars:chars.append(c)
 if len(chars)>256:raise ValueError('Font exceeds 256 glyphs')
 font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',14)
 mono=ImageFont.truetype('C:/Windows/Fonts/consolab.ttf',20)
 rows=[]
 for i in range(256):
  img=Image.new('1',(16,16),0)
  if i<len(chars) and i>=32:
   d=ImageDraw.Draw(img);box=d.textbbox((0,0),chars[i],font=font)
   if i<128:
    tmp=Image.new('1',(16,18),0);td=ImageDraw.Draw(tmp)
    td.text((2,-1),chars[i],font=mono,fill=1)
    img=tmp.resize((16,16),Image.Resampling.NEAREST)
   else:d.text(((16-(box[2]-box[0]))//2-box[0],1-box[1]),chars[i],font=font,fill=1)
  rows.extend(sum(int(bool(img.getpixel((x,y))))<<(15-x) for x in range(16)) for y in range(16))
 dest=a.source_dir/'yolo/sources';dest.mkdir(parents=True,exist_ok=True)
 (dest/'benchmark_font.hex').write_text(''.join(f'{r:04x}\n' for r in rows),encoding='ascii')
 header='/* Generated by generate_benchmark_assets.py. Glyph indices, not UTF-8. */\n'
 for key,value in LABELS.items():
  encoded=''.join('\\x'+format(chars.index(c),'02x') for c in value)
  header+=f'#define BM_{key} "{encoded}"\n'
 (a.source_dir/'yolo/software/benchmark_text.h').write_text(header,encoding='ascii')
 print(f'Generated {len(chars)} glyphs, 4096 x 16-bit font words')

if __name__=='__main__':main()
